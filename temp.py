# ------------------------------------------------------------------------------
#                    FLIGHT CORRUPTION TYPE ASSIGNMENT
# ------------------------------------------------------------------------------
def assignCorruptionTypes(flight_ids: List[str], corruption_names: List[str],
                          seed: int) -> Dict[str, str]:
    """
    Assigns every flight ID a corruption type.

    Every flight in flight_ids is corrupted -- there is no held-out clean pool
    here, since the clean control copy is now generated separately (and
    unconditionally) for every flight in CLEAN_CONTROL_DATA_ROOT. This function
    only decides which corruption type each flight receives, distributing them
    round-robin (after shuffling) so each corruption type gets a roughly equal
    share of flights.

    Args:
        flight_ids (List[str]): All candidate flight IDs (from test.txt).
        corruption_names (List[str]): Corruption type keys to distribute across.
        seed (int): Random seed for reproducibility.

    Returns:
        Dict[str, str]: Mapping of flight_id -> corruption_name.
    """
    # Create a Shuffled Copy so the Original List Order is Preserved Elsewhere.
    shuffled = flight_ids[:]
    random.seed(seed)
    random.shuffle(shuffled)

    # Distribute Every Flight Round-Robin Across Corruption Types.
    assignment: Dict[str, str] = {}
    for idx, flight_id in enumerate(shuffled):
        corruption_name = corruption_names[idx % len(corruption_names)]
        assignment[flight_id] = corruption_name

    # Return the Completed Assignment.
    return assignment
