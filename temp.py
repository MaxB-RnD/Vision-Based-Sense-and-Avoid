# ------------------------------------------------------------------------------
#                               MAIN EXECUTION
# ------------------------------------------------------------------------------
def main() -> None:
    """
    Entry point for building the corrupted introspection test set.
    """
    # Print a Blank Line for Cleaner Console Output Spacing.
    print()

    # Validate that All Configured Corruption Types Exist in the Registry.
    for name in ACTIVE_CORRUPTIONS:
        if name not in CORRUPTION_REGISTRY:
            raise ValueError(
                "ACTIVE_CORRUPTIONS Contains Unknown Key '%s'. Available: %s"
                % (name, list(CORRUPTION_REGISTRY.keys()))
            )

    # Load the Flight IDs from the Test Split.
    log(LogLevel.INFO, "build_corrupted_test_set:main", "Reading: %s", INPUT_TEST_FLIGHTS_PATH)
    flight_ids = parseFlightIds(INPUT_TEST_FLIGHTS_PATH)
    log(LogLevel.INFO, "build_corrupted_test_set:main", "Found: %d flight IDs in test.txt", len(flight_ids))

    # Assign Every Flight a Corruption Type. Every Flight in Test.txt is
    # Corrupted -- the Clean Control Copy of the Same Flight is Written
    # Separately and Unconditionally Below.
    assignment = assignCorruptionTypes(flight_ids, ACTIVE_CORRUPTIONS, SEED)

    # Load the Dataset Metadata Without Triggering a Fresh Download.
    dataset = dataLoader(download=False)

    # Initialise Containers for the Manifest and Flight Subsets.
    manifest_entries = []
    corrupted_by_type: Dict[str, List[str]] = {name: [] for name in ACTIVE_CORRUPTIONS}
    corruption_failed_flights: List[str] = []
    control_flights: List[str] = []

    # Get the Total Number of Flights to Process. 
    total = len(flight_ids)

    # Process Each Flight: Corrupt it into OUTPUT_DATA_ROOT, and Unconditionally
    # Copy the Same Flight Unmodified into CLEAN_CONTROL_DATA_ROOT.
    for idx, flight_id in enumerate(flight_ids):
        # Retrieve the Corruption Assignment for the Current Flight.
        corruption_name = assignment[flight_id]

        print("Flight %d/%d  %s  -->  %s (+ clean control)" % (idx + 1, total, flight_id, corruption_name))
        entry = corruptFlight(dataset, flight_id, corruption_name)

        # Fall Back to an Unmodified Copy in OUTPUT_DATA_ROOT if the Flight
        # Could Not Actually be Corrupted (e.g. too short). It is Excluded
        # from the Per-Type Corrupted Lists so it isn't Miscounted as a
        # Genuine Corrupted Sample, but its Clean Control Copy is Still Made.
        if entry is None:
            copyCleanFlight(flight_id, OUTPUT_DATA_ROOT)
            corruption_failed_flights.append(flight_id)
        else:
            manifest_entries.append(entry)
            corrupted_by_type[corruption_name].append(flight_id)

        # Write the Clean Control Copy of the Identical Flight, Regardless of
        # Whether the Corruption Above Succeeded.
        copyCleanFlight(flight_id, CLEAN_CONTROL_DATA_ROOT)
        control_flights.append(flight_id)

    # Copy the ImageSets Folder for Each Part Used by the Test Split, into
    # Both the Corrupted Dataset and the Clean Control Dataset.
    copied_parts = copyImageSetFolders(flight_ids, OUTPUT_DATA_ROOT)
    copyImageSetFolders(flight_ids, CLEAN_CONTROL_DATA_ROOT)
    print()
    log(LogLevel.INFO, "build_corrupted_test_set:main",
        "Copied ImageSet folders for %d parts to: %s and %s",
        len(copied_parts), OUTPUT_DATA_ROOT, CLEAN_CONTROL_DATA_ROOT)

    # Write a Flight List for Each Corruption Type.
    print()
    for corruption_name, ids in corrupted_by_type.items():
        writeFlightListFile(
            ids,
            filepath=os.path.join(OUTPUT_RECORDS_DIR, "%s_flights.txt" % corruption_name),
            description=(
                "Flight IDs from test.txt that were corrupted with '%s' for the\n"
                "introspection gradual-degradation test set." % corruption_name
            ),
        )

    # Write the Flight List for Flights that Could Not be Corrupted (Fell Back
    # to an Unmodified Copy in the Corrupted Dataset).
    if corruption_failed_flights:
        writeFlightListFile(
            corruption_failed_flights,
            filepath=os.path.join(OUTPUT_RECORDS_DIR, "corruption_failed_flights.txt"),
            description=(
                "Flight IDs from test.txt that could not be corrupted (e.g. too\n"
                "short for the configured ramp) and were left unmodified in the\n"
                "corrupted dataset as a fallback. Their clean control copy still\n"
                "exists in CLEAN_CONTROL_DATA_ROOT like every other flight."
            ),
        )

    # Write the Flight List for the Clean Control Set. This is EVERY Flight in
    # test.txt -- Each One has an Identical Clean Counterpart to its Corrupted
    # Version, so Failure Rate can be Compared Flight-for-Flight Against Clean.
    writeFlightListFile(
        control_flights,
        filepath=os.path.join(OUTPUT_RECORDS_DIR, "clean_control_flights.txt"),
        description=(
            "Flight IDs from test.txt, each copied unmodified into\n"
            "CLEAN_CONTROL_DATA_ROOT as the clean control counterpart of the\n"
            "identically-named flight in the corrupted dataset."
        ),
    )

    # Write the Corruption Configuration and Per-Flight Results to JSON.
    manifest_path = os.path.join(OUTPUT_RECORDS_DIR, "corruption_manifest.json")
    with open(manifest_path, 'w') as f:
        json.dump({
            "seed": SEED,
            "active_corruptions": ACTIVE_CORRUPTIONS,
            "ramp_shape": RAMP_SHAPE,
            "ramp_length_frames": RAMP_LENGTH_FRAMES,
            "peak_severity": PEAK_SEVERITY,
            "onset_fraction_range": list(ONSET_FRACTION_RANGE),
            "clean_control_data_root": CLEAN_CONTROL_DATA_ROOT,
            "flights": manifest_entries,
            "corruption_failed_flights": corruption_failed_flights,
        }, f, indent=2)

    # Report the Location and Number of Corrupted Flights in the Manifest.
    log(LogLevel.INFO, "build_corrupted_test_set:main",
        "Manifest Written: %s (%d corrupted flights)", manifest_path, len(manifest_entries))

    # Generate Videos for Three Flights from Each Dataset Part.
    visualiseFlights(flight_ids)

    # Display the Final Clean-Control, Corrupted, and Per-Type Flight Counts.
    print()
    log(LogLevel.INFO, "build_corrupted_test_set:main",
        "Done.  Clean Control: %d  |  Corrupted: %d  (%s)  |  Corruption Failed (Fallback): %d  |  Total: %d.\n",
        len(control_flights), len(manifest_entries),
        ", ".join("%s: %d" % (k, len(v)) for k, v in corrupted_by_type.items()),
        len(corruption_failed_flights), total)
# ------------------------------------------------------------------------------


# Call the Main Function
if __name__ == "__main__":
    main()