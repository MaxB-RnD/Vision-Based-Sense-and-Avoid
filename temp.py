# Source Test Flight List.
INPUT_TEST_FLIGHTS_PATH = 'configs/datasets/training_subsets/test.txt'

# Output Directory for Flight Lists & the Corruption Manifest.
OUTPUT_RECORDS_DIR = 'configs/datasets/corruption_subsets'

# Set Output Root of New Corrupted Dataset.
OUTPUT_DATA_ROOT = os.path.join('data', 'corruption_dataset')

# Set Output Root of the Clean Control Dataset. Holds an Unmodified Copy of
# Every Flight that also Appears (Corrupted) in OUTPUT_DATA_ROOT, so Failure
# Rate can be Compared Against the Same Flights Under Clean Conditions.
CLEAN_CONTROL_DATA_ROOT = os.path.join('data', 'corruption_dataset_clean_control')

# Random Seed for Reproducibility.
SEED = 42

# Corruption Types to Apply.
ACTIVE_CORRUPTIONS = ['iso_noise', 'defocus_blur', 'colour_quantisation']

# Ramp Configuration. See severity_scheduler.py for Shape Definitions.
RAMP_SHAPE = 'linear'
RAMP_LENGTH_FRAMES = 30
PEAK_SEVERITY = 1.0

# Minimum Clean Frames Before Ramp Starts.
MIN_CLEAN_LEAD_FRAMES = 20

# Fractional Range for Randomly Selecting the Corruption Onset.
ONSET_FRACTION_RANGE = (0.30, 0.65)

# Minimum Flight Length Required for Corruption (Lead-In + Ramp Duration + Post-Ramp).
MIN_TRACK_LENGTH_FOR_CORRUPTION = MIN_CLEAN_LEAD_FRAMES + RAMP_LENGTH_FRAMES + 10
