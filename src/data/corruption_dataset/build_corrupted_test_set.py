# Builds a gradually-degrading introspection test dataset from the existing
# test.txt split by applying continuous, ramping image corruptions to a
# configurable portion of the flights.
#
# Flights selected for corruption are processed frame-by-frame using the
# corruption functions defined in corruptions.py and the severity schedules
# generated by severity_scheduler.py. The remaining flights are copied
# unchanged into the output dataset as the clean portion of the test set.
#
# The script also generates flight lists for each corruption type and for the
# clean flights, together with a corruption_manifest.json containing the
# corruption parameters and onset information for each successfully corrupted
# flight.
#
# USAGE INSTRUCTIONS:
#   1. Run the Script from the Project Root:
#       - python -m src.data.corruption_dataset.build_corrupted_test_set
#
#   2. Optional Environment Variables:
#       - INPUT_TEST_FLIGHTS_PATH
#           Path to the test.txt flight split used as the source population.
#
#       - OUTPUT_RECORDS_DIR
#           Directory where the generated flight lists and corruption manifest are
#           written.
#
#       - OUTPUT_DATA_ROOT
#           Root directory for the generated non-destructive dataset.
#
#       - CORRUPTED_FRACTION
#           Fraction of test flights selected for corruption. The remainder are copied
#           unchanged as clean flights.
#
#       - ACTIVE_CORRUPTIONS
#           List of corruption types to distribute across the selected flights.
#           Values must match keys registered in CORRUPTION_REGISTRY.
#
#       - RAMP_SHAPE
#           Severity ramp shape used when applying corruption. Must match a shape
#           registered in severity_scheduler.py.
#
#       - RAMP_LENGTH_FRAMES
#           Number of frames over which corruption severity increases from zero to the
#           configured peak severity.
#
#       - PEAK_SEVERITY
#           Maximum corruption severity reached after the ramp.
#
#       - ONSET_FRACTION_RANGE
#           Fractional range of each flight within which the corruption onset frame
#           may be selected.
#
#       - MIN_TRACK_LENGTH_FOR_CORRUPTION
#           Minimum number of frames required for a flight to be corrupted. Flights
#           shorter than this threshold fall back to the clean dataset.
