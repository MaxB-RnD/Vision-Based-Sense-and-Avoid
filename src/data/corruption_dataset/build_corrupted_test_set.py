# ------------------------------------------------------------------------------
#                    DATASET STRUCTURE & COPY HELPERS
# ------------------------------------------------------------------------------
def partPrefixFromFlightId(flight_id: str) -> str:
    """
    Extracts the dataset part prefix (e.g. 'part1') from a flight ID.

    Args:
        flight_id (str): Full flight ID (e.g. 'part1abc123...').

    Returns:
        str: Part prefix (e.g. 'part1').
    """
    # Slice the First 5 Characters.
    return flight_id[:5]


def copyCleanFlight(flight_id: str) -> None:
    """
    Copies a clean flight from the original dataset into the merged
    corruption dataset without modifying any of the original files.

    Args:
        flight_id (str): Full flight ID (e.g. 'part1abc123...').

    Returns:
        None
    """
    # Resolve the Dataset Part from the Flight ID.
    part = partPrefixFromFlightId(flight_id)

    # Build the Source & Destination Flight Paths.
    source_dir = os.path.join('data', 'original_dataset', part, 'Images', flight_id)
    output_dir = os.path.join(OUTPUT_DATA_ROOT, part, 'Images', flight_id)

    # Skip the Flight if its Source Directory is Missing.
    if not os.path.isdir(source_dir):
        log(
            LogLevel.WARNING, "build_corrupted_test_set:copyCleanFlight",
            "Source directory does not exist for clean flight %s: %s", flight_id, source_dir)
        return

    # Copy the Flight Without Modifying the Original Dataset.
    shutil.copytree(source_dir, output_dir, dirs_exist_ok=True)


def copyImageSetFolders(flight_ids: List[str]) -> List[str]:
    """
    Copies the ImageSets folder for each dataset part represented in the 
    supplied flight IDs into the new corruption dataset.

    Returns:
        List[str]: Parts whose ImageSet folders were successfully copied.
    """
    # Get the Unique Dataset Parts Represented by the Flights.
    parts = sorted({partPrefixFromFlightId(flight_id) for flight_id in flight_ids})

    # Track the Parts Whose ImageSets Folders were Copied.
    copied_parts = []

    # Copy the ImageSets Folder for Each Represented Dataset Part.
    for part in parts:
        # Build the Source & Destination ImageSets Paths.
        source_dir = os.path.join('data', 'original_dataset', part, 'ImageSets')
        destination_dir = os.path.join(OUTPUT_DATA_ROOT, part, 'ImageSets')

        # Skip the Part if its ImageSets Folder is Missing.
        if not os.path.isdir(source_dir):
            log(LogLevel.WARNING, "build_corrupted_test_set:copyImageSetFolders",
                "ImageSet folder not found for %s: %s", part, source_dir)
            continue

        # Copy the Entire ImageSet Folder into the New Dataset.
        shutil.copytree(source_dir, destination_dir, dirs_exist_ok=True)
        copied_parts.append(part)

    # Return the Parts Whose ImageSets Folder Were Copied.
    return copied_parts
