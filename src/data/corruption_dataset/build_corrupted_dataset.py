# ------------------------------------------------------------------------------
def writeFlightListFile(flight_ids: List[str], filepath: str, description: str) -> None:
    """
    Writes a formatted flight ID list to disk for later subset evaluation.

    The output file includes a standard header containing the supplied 
    description, random seed, and total flight count, followed by the flight 
    IDs.

    Args:
        flight_ids (List[str]): Flight IDs to write.
        filepath (str): Output file path.
        description (str): Short description written into the file header.

    Returns:
        None:
    """
    # Ensure the Output Directory Exists.
    os.makedirs(os.path.dirname(filepath), exist_ok=True)

    # Construct the File Header.
    header = (
        "--------------------------------------------------------------------------------\n"
        "-                           D E S C R I P T I O N                              -\n"
        "--------------------------------------------------------------------------------\n"
        "\n"
        + description + "\n"
        "\n"
        "This file is auto-generated by build_corrupted_dataset.py. DO NOT EDIT IT\n"
        "MANUALLY. Re-run the script to regenerate.\n"
        "\n"
        "Seed: %d  |  Total: %d\n"
        "\n"
        "--------------------------------------------------------------------------------\n"
        "\n"
        "# FLIGHT IDs\n"
    ) % (SEED, len(flight_ids))

    # Write Header & Flight IDs.
    with open(filepath, 'w') as f:
        f.write(header)
        f.write('\n'.join(flight_ids) + ('\n' if flight_ids else ''))

    # Print Info Message.
    log(LogLevel.INFO, "build_corrupted_dataset:writeFlightListFile",
        "Written: %s (%d flights)", filepath, len(flight_ids))
