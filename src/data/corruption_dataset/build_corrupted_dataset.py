# ------------------------------------------------------------------------------
#                           SINGLE FLIGHT CORRUPTION
# ------------------------------------------------------------------------------
def corruptFlight(dataset, flight_id: str, corruption_name: str) -> Optional[Dict]:
    """
    Applies a ramping corruption to every frame of a single flight and writes
    the result to OUTPUT_DATA_ROOT, without modifying the original images.

    Args:
        dataset: Loaded AOT Dataset object.
        flight_id (str): Flight ID to corrupt.
        corruption_name (str): Key into corruptions.CORRUPTION_REGISTRY.

    Returns:
        Optional[Dict]: Manifest entry for this flight, or None if the flight
                        could not be processed (missing metadata, too short,
                        or a frame failed to load).
    """
    # Look up the Corruption Function from the Registry.
    corrupt_fn = CORRUPTION_REGISTRY[corruption_name]

    try:
        # Retrieve the Flight Object & its Frames.
        flight = dataset.get_flight(flight_id)
        frames = flight.frames
    except Exception as e:
        # Log the Failure and Skip the Flight.
        log(LogLevel.WARNING, "build_corrupted_dataset:corruptFlight",
            "Could Not Load Metadata for Flight %s: %s. Skipping.", flight_id, str(e))
        return None

    # Get the Frame IDs and Total Frame Count.
    frame_ids = list(frames.keys())
    num_frames = len(frame_ids)

    # Skip Flights too Short for a Meaningful Onset + Ramp + Post-Ramp Region.
    if num_frames < MIN_TRACK_LENGTH_FOR_CORRUPTION:
        log(LogLevel.WARNING, "build_corrupted_dataset:corruptFlight",
            "Flight %s has Only %d Frames (< %d). Skipping Corruption, Treating as Clean.",
            flight_id, num_frames, MIN_TRACK_LENGTH_FOR_CORRUPTION)
        return None

    # Ensure the Flight has Enough Frames to Satisfy the Clean Lead-In Plus Ramp.
    latest_valid_onset = num_frames - RAMP_LENGTH_FRAMES - 1
    if MIN_CLEAN_LEAD_FRAMES >= latest_valid_onset:
        log(LogLevel.WARNING, "build_corrupted_dataset:corruptFlight",
            "Flight %s Too Short (%d frames) for MIN_CLEAN_LEAD_FRAMES=%d + Ramp. Skipping Corruption.", flight_id, num_frames, MIN_CLEAN_LEAD_FRAMES)
        return None

    # Calculate Fraction-Based Bounds, Constrained by the Hard Clean Lead Floor.
    low_frac, high_frac = ONSET_FRACTION_RANGE
    earliest_onset = max(MIN_CLEAN_LEAD_FRAMES, int(num_frames * low_frac))
    latest_onset = min(latest_valid_onset, max(earliest_onset, int(num_frames * high_frac) - RAMP_LENGTH_FRAMES))

    # Ensure a Valid Integer Range for Random Selection.
    if earliest_onset > latest_onset:
        onset_frame = earliest_onset
    else:
        onset_frame = random.randint(earliest_onset, latest_onset)

    # Build the Per-Frame Severity Schedule for this Track.
    severity_schedule = buildSeveritySchedule(
        num_frames=num_frames,
        onset_frame=onset_frame,
        ramp_length=RAMP_LENGTH_FRAMES,
        peak_severity=PEAK_SEVERITY,
        shape=RAMP_SHAPE,
    )

    # Resolve & Create the Output Directory for this Flight.
    part = partPrefixFromFlightId(flight_id)
    output_dir = os.path.join(OUTPUT_DATA_ROOT, part, 'Images', flight_id)
    os.makedirs(output_dir, exist_ok=True)

    # Prepare to Compute the Dataset Quality Metrics. 
    scr_curve: List[Optional[float]] = [None] * num_frames
    psnr_at_peak_values: List[float] = []
    background_complexity: Optional[float] = None

    # Apply the Corruption Frame-by-Frame According to the Severity Schedule.
    frames_written = 0
    for i, frame_id in enumerate(frame_ids):
        # Get the Scheduled Corruption Severity for this Frame.
        severity = severity_schedule[i]

        try:
            # Load the Original Frame as a NumPy Array (Read-Only Access).
            image = frames[frame_id].image(type='numpy')
        except Exception as e:
            # Log the Failure and Skip This Frame.
            log(LogLevel.WARNING, "build_corrupted_dataset:corruptFlight",
                "Could Not Load Frame %s in Flight %s: %s. Skipping Frame.",
                frame_id, flight_id, str(e))
            continue

        # Apply the Corruption Function at this Frame's Severity Level.
        corrupted_image = corrupt_fn(image, severity)

        # Resolve the Primary Ground-Truth BBox for this Frame, if Any.
        bbox = getPrimaryBoundingBox(frames[frame_id])

        if bbox is not None:
            # Track SCR on the Corrupted Frame for the Ramp/Terminal Metrics.
            scr_curve[i] = computeLocalSCR(corrupted_image, bbox)

            # Capture Background Complexity Once at the First Available Valid BBox.
            if background_complexity is None:
                background_complexity = computeBackgroundComplexity(image, bbox)

        # Track PSNR Once the Ramp has Reached Peak Severity, for Cross-Corruption-Type Calibration.
        if severity >= PEAK_SEVERITY:
            psnr_at_peak_values.append(computePSNR(image, corrupted_image))

        # Preserve the Original Image Filename.
        original_image_path = frames[frame_id].image_path()
        output_filename = os.path.basename(original_image_path)

        # Write the Corrupted Image Using the Original Filename.
        output_path = os.path.join(output_dir, output_filename)
        cv2.imwrite(output_path, corrupted_image)
        frames_written += 1

    # Guard Against a Flight where No Frames Could be Written.
    if frames_written == 0:
        log(LogLevel.ERROR, "build_corrupted_dataset:corruptFlight",
            "No Frames Could be Written for Flight %s. Skipping.", flight_id)
        return None

    # Derive the Terminal SCR from the "Held at Peak" Tail Region.
    tail_start = min(onset_frame + RAMP_LENGTH_FRAMES, num_frames)
    tail_scrs = [v for v in scr_curve[tail_start:] if v is not None]
    terminal_scr = float(np.mean(tail_scrs)) if tail_scrs else None

    # Derive Ramp Quality Metrics from the Ramp Window.
    scr_monotonicity = computeRampMonotonicity(scr_curve, onset_frame, RAMP_LENGTH_FRAMES)
    scr_ramp_coverage = computeRampCoverage(scr_curve, onset_frame, RAMP_LENGTH_FRAMES)

    # Derive Peak Quality Metrics.
    psnr_at_peak = float(np.mean(psnr_at_peak_values)) if psnr_at_peak_values else None

    # Build & Return the Manifest Entry for this Flight.
    return {
        "flight_id":              flight_id,
        "corruption_type":        corruption_name,
        "num_frames":             num_frames,
        "frames_written":         frames_written,
        "onset_frame":            onset_frame,
        "ramp_shape":             RAMP_SHAPE,
        "ramp_length":            RAMP_LENGTH_FRAMES,
        "peak_severity":          PEAK_SEVERITY,
        "output_dir":             output_dir,

        # No-Inference Dataset Quality Metrics.
        "terminal_scr":           terminal_scr,
        "scr_monotonicity":       scr_monotonicity,
        "scr_ramp_coverage":      scr_ramp_coverage,
        "background_complexity":  background_complexity,
        "psnr_at_peak":           psnr_at_peak,
    }
